"""Claim-neutral figures from results/ (G1 tables). Usage: make_figures.py <results_dir>
Writes <results_dir>/figures/{margin_law,cost_law,baselines_q8,break_even}.{pdf,png} and
figures/summary_tables.md.

  margin_law   observed per-token divergence rate vs f_m(0) sigma / sqrt(2 pi) (law_robustness*.json,
               bandwidth 0.1), all parent x task x version cases
  cost_law     r vs mean decode batch (cost/cost_law_points.json, RESULTS.md sec. 36 and 38)
  baselines_q8 Q8_0 worst-slice harm UCB at equal compute, GSM8K, B1 / B2m / B3 / ours
               (baselines/*_mgf_*.json)
  break_even   break-even audit rate vs r (regime_map.json)
"""
import json
import sys
from glob import glob
from pathlib import Path

import matplotlib
import matplotlib.ticker
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

R = Path(sys.argv[1])
F = R / "figures"
F.mkdir(exist_ok=True)
NAMES = {"full_truth": "Qwen-3B GSM8K", "q7_truth": "Qwen-7B GSM8K", "q14_truth": "Qwen-14B GSM8K",
         "l8_truth": "Llama-8B GSM8K", "phi_truth": "Phi-3.5 GSM8K", "smol_truth": "SmolLM2 GSM8K",
         "mmlu_truth": "Qwen-3B MMLU-Pro", "phim_truth": "Phi-3.5 MMLU-Pro", "q14m_truth": "Qwen-14B MMLU-Pro",
         "l8m_truth": "Llama-8B MMLU-Pro", "imat_truth": "Qwen-3B GSM8K imatrix",
         "mimat_truth": "Qwen-3B MMLU-Pro imatrix"}
VMARK = {"Q8_0": "o", "Q6_K": "s", "Q4_K_M": "^", "Q3_K_M": "D"}
md = ["# Summary tables (generated by src/make_figures.py)", ""]


def save(fig, name):
    fig.tight_layout()
    fig.savefig(F / f"{name}.pdf")
    fig.savefig(F / f"{name}.png", dpi=150)
    plt.close(fig)


# 1. margin law
law = {}
for f in sorted(glob(str(R / "law_robustness*.json"))):
    law.update(json.loads(Path(f).read_text()))
fig, ax = plt.subplots(figsize=(5, 4.2))
cmap = plt.get_cmap("tab10")
rows, ratios = [], []
for i, (t, vs) in enumerate(law.items()):
    for v, bw in vs.items():
        x = bw["0.1"]
        pred = x["f0"] * x["sigma"] / np.sqrt(2 * np.pi)
        ax.scatter(pred, x["rho"], marker=VMARK[v], color=plt.get_cmap("tab20")(i % 20), s=28,
                   label=NAMES.get(t, t) if v == next(iter(vs)) else None)
        rows.append((NAMES.get(t, t), v, x["f0"], x["sigma"], x["rho"], x["ratio"]))
        ratios.append(x["ratio"])
lim = np.array([1e-3, 2])
c = float(np.median(ratios))
ax.plot(lim, lim, "k:", lw=1, label="y = x")
ax.plot(lim, c * lim, "k-", lw=0.8, label=f"y = {c:.2f} x (median)")
ax.set(xscale="log", yscale="log", xlabel=r"predicted $f_m(0)\,\sigma_q/\sqrt{2\pi}$",
       ylabel=r"observed per-token divergence rate $\rho$",
       title=f"Margin law, {len(rows)} cases, bw 0.1 (ratio {min(ratios):.2f}-{max(ratios):.2f})")
ax.legend(fontsize=6.5, loc="upper left")
save(fig, "margin_law")
md += ["## Margin law (bandwidth 0.1)", "", "| Parent / task | version | f_m(0) | sigma_q | rho | obs / pred |",
       "|---|---|---|---|---|---|"]
md += [f"| {a} | {b} | {c_:.3f} | {d:.3f} | {e:.4f} | {g:.2f} |" for a, b, c_, d, e, g in rows]
md.append("")

# 2. cost law
pts = json.loads((R / "cost" / "cost_law_points.json").read_text())
fig, ax = plt.subplots(figsize=(5, 3.8))
for i, (name, p) in enumerate(pts["series"].items()):
    ax.scatter(p["mean_batch"], p["r"], marker="o", color=cmap(i), label=name)
    for b_, r_, note in zip(p["mean_batch"], p["r"], p.get("labels", [""] * len(p["r"]))):
        if note:
            ax.annotate(note, (b_, r_), textcoords="offset points", xytext=(4, -10), fontsize=6.5)
    k = pts["kappa"].get(name)
    if k:
        b = np.linspace(0, max(p["mean_batch"]) * 1.05, 50)
        ax.plot(b, k * b, ls="--", color=cmap(i), lw=0.8)
ax.set(xlabel="mean decode batch $B_{eff}$", ylabel="prefill / decode cost per token $r$",
       title=r"Cost law: $r \approx \kappa B_{eff}$ (dashed)")
ax.legend(fontsize=7)
save(fig, "cost_law")

# 3. baselines, Q8_0 GSM8K
order = ["full_truth", "q7_truth", "q14_truth", "l8_truth", "phi_truth"]
files = {"full_truth": "gsm8k_qwen2.5-3b", "q7_truth": "gsm8k_qwen2.5-7b", "q14_truth": "gsm8k_qwen2.5-14b",
         "l8_truth": "gsm8k_llama-3.1-8b", "phi_truth": "gsm8k_phi-3.5-mini"}
M = [("harm_B1", "B1 (no screening)"), ("B2m", "B2 (AIPW, MGF bound)"), ("B3", "B3 (active design)"),
     ("harm_ours", "ours (exact screening)")]
fig, axes = plt.subplots(1, 2, figsize=(9, 3.6), sharey=True)
md += ["## Q8_0 worst-slice harm UCB at equal compute (GSM8K)", "",
       "| Parent | r, b | true H | B1 | B2 (Bernstein) | B2m | B3 | B4 | ours | best valid baseline / ours |",
       "|---|---|---|---|---|---|---|---|---|---|"]
for ax, (r, bi) in zip(axes, [("0.076", 1), ("0.365", 2)]):
    w = 0.2
    for k, (m, lab) in enumerate(M):
        ys = []
        for t in order:
            js = json.loads((R / "baselines" / f"{files[t]}_mgf_r{r}.json").read_text())["values"]["Q8_0"]
            ys.append(js["methods"][m][bi][0])
        ax.bar(np.arange(len(order)) + (k - 1.5) * w, ys, w, label=lab)
    for j, t in enumerate(order):
        js = json.loads((R / "baselines" / f"{files[t]}_mgf_r{r}.json").read_text())["values"]["Q8_0"]
        ax.plot([j - 2 * w, j + 2 * w], [js["true_worst_H"]] * 2, "k-", lw=1)
        x = js["methods"]
        vals = {m: x[m][bi][0] for m in ("harm_B1", "B2", "B2m", "B3", "B4", "harm_ours")}
        best = min(vals[m] for m in ("harm_B1", "B2", "B2m", "B3", "B4"))
        f = lambda u: "inf" if u == float("inf") else f"{u:.3f}"
        md.append(f"| {NAMES[t]} | {r}, {[0.2, 0.4, 0.6][bi]} | {js['true_worst_H']:.3f} | "
                  + " | ".join(f(vals[m]) for m in ("harm_B1", "B2", "B2m", "B3", "B4", "harm_ours"))
                  + f" | {best / vals['harm_ours']:.2f} |")
    ax.set_xticks(range(len(order)), [NAMES[t].replace(" GSM8K", "") for t in order], fontsize=8)
    ax.set_title(f"r = {r}, budget b = {[0.2, 0.4, 0.6][bi]} x full evaluation", fontsize=9)
axes[0].set_ylabel("mean worst-slice harm UCB (black: true H)")
axes[0].legend(fontsize=7)
save(fig, "baselines_q8")
md.append("")

# 4. break-even audit rate
reg = json.loads((R / "regime_map.json").read_text())["break_even"]
fig, ax = plt.subplots(figsize=(5, 3.8))
for i, (key, d) in enumerate(reg.items()):
    t, v = key.split(":")
    if v not in ("Q8_0", "Q6_K"):
        continue
    rs = sorted(d, key=float)
    ax.plot([float(x) for x in rs], [d[x] for x in rs], marker=VMARK[v],
            color=cmap(list(NAMES).index(t) % 10) if t in NAMES else "gray", label=f"{NAMES.get(t, t)} {v}")
ax.axhline(1, color="k", lw=0.8, ls=":")
ax.set(xlabel="prefill / decode cost ratio r", ylabel="break-even audit rate $\\pi^*$",
       title="Token cost model: screening cheaper than B1 when $\\pi > \\pi^*$")
ax.set_ylim(0, 1.6)
ax.legend(fontsize=6.5)
save(fig, "break_even")

# 5. measured end-to-end speedup vs decode batch (speed_g1/, speed_bs/; RESULTS.md sec. 48-50)
def speed(d, v, pc):
    s = json.loads((d / f"scr_{v}_k1{'_pc' if pc else ''}.json").read_text())["seconds"]
    return json.loads((d / f"gen_{v}.json").read_text())["seconds"]["full_s"] / (
        s["prefill_s"] + s["scan_s"] + s["cont_s"])

SB = R / "speed_bs"
if SB.exists():
    fig, ax = plt.subplots(figsize=(5, 3.8))
    g1 = R / "speed_g1"
    bs, sp = [], []
    for b in (32, 64, 128):
        if (SB / f"qwen3b_bs{b}").exists():
            bs.append(b); sp.append(speed(SB / f"qwen3b_bs{b}", "Q8_0", True))
    if (g1 / "scr_fp32_Q8_0_k1_pc.json").exists():
        s = json.loads((g1 / "scr_fp32_Q8_0_k1_pc.json").read_text())["seconds"]
        bs.append(256); sp.append(json.loads((g1 / "gen_fp32_Q8_0.json").read_text())["seconds"]["full_s"]
                                  / (s["prefill_s"] + s["scan_s"] + s["cont_s"]))
    ax.plot(bs, sp, "o-", color="k", label="Qwen-3B Q8_0 (batch sweep)")
    tags = {"qwen7b": "Qwen-7B", "qwen14b": "Qwen-14B", "llama8b": "Llama-8B", "phi35": "Phi-3.5"}
    for j, (tg, nm) in enumerate(tags.items()):
        d = SB / f"{tg}_bs32"
        if d.exists():
            for v, mk in (("Q8_0", "o"), ("Q6_K", "s")):
                ax.scatter([32 * (1 + 0.04 * (j + 1))], [max(speed(d, v, False), speed(d, v, True))], marker=mk,
                           color=cmap(j + 1), label=f"{nm} (batch 32)" if v == "Q8_0" else None)
    d = SB / "qwen3b_bs32"
    if d.exists():
        ax.scatter([32], [speed(d, "Q6_K", True)], marker="s", color="k")
    ax.axhline(1.5, color="r", lw=0.8, ls="--", label="G1 threshold 1.5x")
    ax.axhline(1.0, color="k", lw=0.6, ls=":")
    ax.set(xscale="log", xlabel="max decode batch (max_num_seqs)", ylabel="measured end-to-end speedup",
           title="Exact screening + continuation vs full generation (circles Q8_0, squares Q6_K)")
    ax.set_xticks([32, 64, 128, 256]); ax.set_xticklabels(["32", "64", "128", "256"])
    ax.xaxis.set_minor_formatter(matplotlib.ticker.NullFormatter())
    ax.title.set_fontsize(8)
    ax.legend(fontsize=6.5)
    save(fig, "speedup_vs_batch")

# 6. G3 at equal wall-clock (g3_wallclock*.json; RESULTS.md sec. 47, 49, 50)
files = [("batch 256", R / "g3_wallclock.json"), ("batch 32", R / "g3_wallclock_bs32.json")]
if all(f.exists() for _, f in files):
    fig, axes = plt.subplots(1, 2, figsize=(9, 3.6), sharey=True)
    for ax, (lab, f) in zip(axes, files):
        js = json.loads(f.read_text())
        par = [p for p in js if "GSM8K" in p]
        for k, (v, b) in enumerate([("Q8_0", "0.4"), ("Q8_0", "0.6"), ("Q6_K", "0.6")]):
            ys = []
            for p in par:
                x = js[p][v]["values"][b]
                ys.append(x["B1"] / x["ours_full"] if np.isfinite(x["ours_full"]) and x["ours_full"] > 0 else 0.0)
            ax.bar(np.arange(len(par)) + (k - 1) * 0.27, ys, 0.27, label=f"{v}, b = {b}")
        ax.axhline(1.5, color="r", lw=0.8, ls="--")
        ax.axhline(1.0, color="k", lw=0.6, ls=":")
        ax.set_xticks(np.arange(len(par)))
        ax.set_xticklabels([p.replace(" GSM8K", "").replace("Qwen2.5-", "Qwen-") for p in par], fontsize=7, rotation=20)
        ax.set_title(f"G3 at equal wall-clock, {lab} (0 = infeasible at budget b)", fontsize=9)
    axes[0].set_ylabel("B1 / ours (worst-slice harm UCB)")
    axes[0].legend(fontsize=7)
    save(fig, "g3_wallclock")

(F / "summary_tables.md").write_text("\n".join(md) + "\n", encoding="utf-8")
