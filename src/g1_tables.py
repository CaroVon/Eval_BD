"""Frozen main tables for G1, computed directly from the truth matrices and baseline outputs.

Table 1  truth matrices: accuracy, screening power |A|/|P|, harm / repair flips, theta, lemma 3 checks.
Table 2  worst-slice harm UCB at equal compute: B1, ours, best other valid baseline (B2, B2m, B3, B4;
         B6 is excluded because it undercovers, B2s because it uses exact screening itself),
         ratio = min(B1, best other) / ours.
Usage: g1_tables.py <scratch_root> <out.md>
  <scratch_root> holds the truth directories (see TRUTH) and res/baselines/.
"""
import json
import sys
from pathlib import Path

root, out = Path(sys.argv[1]), Path(sys.argv[2])
VERS = ["Q8_0", "Q6_K", "Q4_K_M", "Q3_K_M"]
# (label, truth dir, baselines file stem); stems as in results/baselines/
TRUTH = [
    ("Qwen2.5-3B GSM8K", "full_truth", "gsm8k_qwen2.5-3b"),
    ("Qwen2.5-7B GSM8K", "q7_truth", "gsm8k_qwen2.5-7b"),
    ("Qwen2.5-14B GSM8K", "q14_truth", "gsm8k_qwen2.5-14b"),
    ("Llama-3.1-8B GSM8K", "l8_truth", "gsm8k_llama-3.1-8b"),
    ("Phi-3.5-mini GSM8K", "phi_truth", "gsm8k_phi-3.5-mini"),
    ("SmolLM2-1.7B GSM8K", "smol_truth", "gsm8k_smollm2-1.7b"),
    ("Qwen2.5-3B MMLU-Pro 1k", "mmlu_truth", "mmlupro1000_qwen2.5-3b"),
    ("Qwen2.5-14B MMLU-Pro 1k", "q14m_truth", "mmlupro1000_qwen2.5-14b"),
    ("Llama-3.1-8B MMLU-Pro 1k", "l8m_truth", "mmlupro1000_llama-3.1-8b"),
    ("Phi-3.5-mini MMLU-Pro 1k", "phim_truth", "mmlupro1000_phi-3.5-mini"),
    ("Qwen2.5-3B GSM8K imatrix", "imat4_truth", None),
]
OTHER = ["B2", "B2m", "B3", "B4"]
SETTINGS = [(0.076, 0.4), (0.076, 0.6), (0.365, 0.6)]


def records(td, v):
    f = root / td / "screen" / v / "records.jsonl"
    return [json.loads(l) for l in open(f)] if f.exists() else None


md = ["# G1 main tables (frozen, generated by src/g1_tables.py)", "",
      "fp32, batch-invariant vLLM, A100; llama.cpp ladder dequantized to fp32 (Track A). "
      "The imatrix row reuses the plain Q8_0 (Q8_0 ignores the imatrix).", "",
      "## Table 1. Truth matrices", "",
      "| Parent / task | n | parent acc | version | child acc | \\|A\\|/\\|P\\| | H / Rep | theta | "
      "flips outside D | lemma 3b fails |",
      "|---|---|---|---|---|---|---|---|---|---|"]
for lab, td, _ in TRUTH:
    for v in VERS:
        R = records(td, v)
        if R is None:
            continue
        n = len(R)
        P = [r for r in R if r["parent_correct"]]
        H = sum(1 for r in P if not r["child_correct"])
        Rep = sum(1 for r in R if not r["parent_correct"] and r["child_correct"])
        flip = [r for r in R if r["parent_correct"] != r["child_correct"]]
        outside = sum(1 for r in flip if not r["in_D"])
        l3b = sum(1 for r in R if r.get("lemma3b_ok") is False)
        md.append(f"| {lab} | {n} | {len(P)/n:.3f} | {v} | {sum(r['child_correct'] for r in R)/n:.3f} | "
                  f"{sum(r['in_D'] for r in P)/len(P):.3f} | {H} / {Rep} | {100*(H-Rep)/n:+.2f}% | "
                  f"{outside} | {l3b} |")

md += ["", "## Table 2. Worst-slice harm UCB at equal compute (delta' = 1.4e-3, mean over reps)", "",
       "Cells: B1 / ours / best other valid baseline (name), ratio = min(B1, other) / ours. "
       "Bold ratio: >= 1.5 (G3). Other baselines: B2, B2m, B3, B4 (B3/B4 and B2m only where "
       "`*_mgf_*` files exist). B6 undercovers and B2s builds on exact screening, so neither "
       "counts as a competitor.", "",
       "| Parent / task | version | true H | " + " | ".join(f"r={r}, b={b}" for r, b in SETTINGS) + " |",
       "|---|---|---|" + "---|" * len(SETTINGS)]
for lab, td, stem in TRUTH:
    for v in ["Q8_0", "Q6_K"]:
        if stem is None and v == "Q8_0":
            continue  # identical to the plain Q8_0 row
        cells, trueH = [], None
        for r, b in SETTINGS:
            meth = {}
            files = ([root / "res" / "baselines" / f"{stem}_r{r}.json",
                      root / "res" / "baselines" / f"{stem}_mgf_r{r}.json"] if stem else
                     [root / td / f"baselines_r{r}.json"])
            for f in files:
                if f.exists():
                    js = json.loads(f.read_text())
                    if v in js["values"]:
                        trueH = js["values"][v]["true_worst_H"]
                        k = js["budgets"].index(b)
                        for m, xs in js["values"][v]["methods"].items():
                            meth.setdefault(m, xs[k][0])
            if "harm_ours" not in meth:
                cells.append("-")
                continue
            b1, ours = meth["harm_B1"], meth["harm_ours"]
            oth = {m: meth[m] for m in OTHER if m in meth}
            om = min(oth, key=oth.get)
            ratio = min(b1, oth[om]) / ours
            rs = f"**{ratio:.2f}**" if ratio >= 1.5 else f"{ratio:.2f}"
            cells.append(f"{b1:.3f} / {ours:.3f} / {oth[om]:.3f} ({om}), {rs}")
        if trueH is not None:
            md.append(f"| {lab} | {v} | {trueH:.3f} | " + " | ".join(cells) + " |")

md += ["", "## Figures", "",
       "- `results/figures/margin_law.pdf`: observed vs predicted per-token divergence rate (all cases).",
       "- `results/figures/break_even.pdf`: regime map, break-even audit rate vs r.",
       "- `results/figures/baselines_q8.pdf`: Q8_0 worst-slice UCB by method.",
       "- `results/figures/cost_law.pdf`: r vs mean decode batch.",
       "- Margin-law table: `results/figures/summary_tables.md`.", ""]
out.write_text("\n".join(md) + "\n", encoding="utf-8")
print("G1_TABLES_DONE", out)
